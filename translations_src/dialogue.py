src = open('../src2/Assets/Dialogue/ending.dialogue', encoding='utf-8').read().split('\n')
tres = open([__import__('glob').glob('../cic/x/.godot/imported/ending.dialogue-*.tres')][0][0], encoding='utf-8').read()
compiled = set(json.loads('"%s"' % t) for t in re.findall(r'&"text": "((?:[^"\\]|\\.)*)"', tres))
out = {}
for n, ru in D.items():
    line = src[n - 1]
    m = re.match(r'^([^:]{1,20}): (.*)$', line)
    en = m.group(2) if m and not line.startswith(('$', '~', '=>')) else line
    assert en in compiled, (n, en)
    out[en] = ru
missing = [t for t in compiled if t not in out and re.search('[A-Za-z]{2,}', t) and t not in ('Fawn.',)]
print('dialogue entries', len(out), 'compiled texts', len(compiled), 'untranslated:', missing)
json.dump(out, open('dialogue_catalog.json', 'w'), ensure_ascii=False, indent=0)
